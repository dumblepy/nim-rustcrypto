#!/usr/bin/env bash
# Branch 85 benchmark runner: Poseidon1 vs Poseidon2 R1CS/native and the
# generic Halo2 IPA shape benchmark.
#
# Usage:
#   bash ci/benchmarks_branch85.sh [ARTIFACT_DIR]
#
# The artifact directory defaults to a fresh mktemp directory. It receives:
#   environment.txt      rustc / cargo / uname / host information
#   poseidon-bench.json  machine-readable Poseidon benchmark JSON
#   ipa-bench.json       machine-readable Halo2 IPA benchmark JSON
#   rss.txt              wall time and peak RSS
#
# Peak RSS comes from /usr/bin/time -v when GNU time is installed. If it is
# not available, this script samples /proc/<pid>/status VmHWM from the outside
# (never from the benchmark process itself) and records that source explicitly.
#
# Native release builds only. This script does not run WASM benchmarks.

set -euo pipefail

script_dir="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
repo_root="$(cd "$script_dir/.." && pwd)"
crate_dir="$repo_root/rustcrypto-ffi"
artifact_dir="${1:-$(mktemp -d "${TMPDIR:-/tmp}/bench-branch85.XXXXXX")}"
target_dir="${CARGO_TARGET_DIR:-$crate_dir/target}"

mkdir -p "$artifact_dir"

echo "artifact dir: $artifact_dir"
echo "building release examples (poseidon_bench, halo2_ipa_bench) ..."
cargo build --locked --release --manifest-path "$crate_dir/Cargo.toml" \
    --example poseidon_bench --example halo2_ipa_bench

{
    echo "date_utc: $(date -u +%Y-%m-%dT%H:%M:%SZ)"
    echo "rustc: $(rustc --version)"
    echo "cargo: $(cargo --version)"
    echo "uname: $(uname -a)"
    echo "nproc: $(nproc 2>/dev/null || echo unavailable)"
    echo "crate_dir: $crate_dir"
    echo "target_dir: $target_dir"
    echo "artifact_dir: $artifact_dir"
} > "$artifact_dir/environment.txt"
cat "$artifact_dir/environment.txt"

time_bin=""
if command -v /usr/bin/time >/dev/null 2>&1; then
    time_bin="/usr/bin/time"
fi
time_flag=""
if [ -n "$time_bin" ] && "$time_bin" -v true >/dev/null 2>&1; then
    time_flag="-v"
fi

# Fallback used when GNU time is unavailable. VmHWM is the kernel's
# high-water mark for the child's resident set size, sampled by this script.
run_with_proc_rss() {
    local json="$1"
    local log="$2"
    shift 2

    local start end pid peak hwm status
    peak=0
    start=$(date +%s%N)
    "$@" > "$json" &
    pid=$!
    while kill -0 "$pid" 2>/dev/null; do
        hwm=$(awk '/^VmHWM:/ { print $2 }' "/proc/$pid/status" 2>/dev/null || true)
        if [ -n "$hwm" ] && [ "$hwm" -gt "$peak" ]; then
            peak="$hwm"
        fi
        sleep 0.02
    done
    set +e
    wait "$pid"
    status=$?
    set -e
    end=$(date +%s%N)
    {
        echo "Elapsed (wall clock) time: $(awk -v s="$start" -v e="$end" \
            'BEGIN { printf "%.3f", (e - s) / 1000000000 }') s"
        echo "Maximum resident set size (kbytes): $peak"
        echo "rss_source: /proc/<pid>/status VmHWM sampled by ci/benchmarks_branch85.sh"
    } > "$log"
    return "$status"
}

run_bench() {
    local name="$1"
    shift
    local json="$artifact_dir/$name.json"
    local log="$artifact_dir/$name.time.txt"

    echo "running $name ..."
    if [ -n "$time_bin" ] && [ "$time_flag" = "-v" ]; then
        "$time_bin" -v -o "$log" "$@" > "$json"
    elif [ -n "$time_bin" ]; then
        "$time_bin" -o "$log" "$@" > "$json"
    else
        run_with_proc_rss "$json" "$log" "$@"
    fi

    if command -v python3 >/dev/null 2>&1; then
        python3 -m json.tool "$json" >/dev/null
    fi
}

run_bench poseidon-bench "$target_dir/release/examples/poseidon_bench"
run_bench ipa-bench "$target_dir/release/examples/halo2_ipa_bench"

{
    echo "# branch 85 native benchmark wall time and peak RSS"
    echo "# generated by ci/benchmarks_branch85.sh"
    if [ -n "$time_bin" ] && [ "$time_flag" = "-v" ]; then
        echo "# rss_source: /usr/bin/time -v"
    elif [ -n "$time_bin" ]; then
        echo "# rss_source: /usr/bin/time (GNU -v unavailable; RSS may be absent)"
    else
        echo "# rss_source: /proc/<pid>/status VmHWM sampled by this script (GNU time absent)"
    fi
} > "$artifact_dir/rss.txt"

for name in poseidon-bench ipa-bench; do
    log="$artifact_dir/$name.time.txt"
    {
        echo "[$name]"
        if [ "$time_flag" = "-v" ]; then
            awk -F': ' '
                /Elapsed \(wall clock\) time/ { printf "wall_time: %s\n", $2 }
                /Maximum resident set size/ { printf "peak_rss_kib: %s\n", $2 }
            ' "$log"
        else
            grep -E "Elapsed|Maximum resident|rss_source" "$log" || true
        fi
    } >> "$artifact_dir/rss.txt"
    rm -f "$log"
done

cat "$artifact_dir/rss.txt"
echo "artifacts:"
ls -l "$artifact_dir"
